// Приводит тексты прежних уроков к роли продуктового маркетолога и обновляет устаревшие факты.
export function toPmmText(s: string): string {
  return s
    .replace(/Вы пришли PM в/g, 'Вы пришли продуктовым маркетологом в')
    .replace(/Вы новый PM в/g, 'Вы новый продуктовый маркетолог в')
    .replace(/Вы — PM\b/g, 'Вы — продуктовый маркетолог')
    .replace(/Вы PM\b/g, 'Вы — продуктовый маркетолог')
    .replace(/Урок для PM/g, 'Урок для PMM')
    .replace(/Инсайт для PM/g, 'Инсайт для PMM')
    .replace(/Тинькофф/g, 'Т-Банк')
    .replace(/Shreys Doshi/g, 'Shreyas Doshi')
    .replace(/\bTwitter\b/g, 'X (Twitter)')
    .replace(/\bPM\b/g, 'PMM');
}

export function toPmmModule(m: Module): Module {
  return {
    ...m,
    title: toPmmText(m.title),
    description: toPmmText(m.description),
    tabs: {
      theory: toPmmText(m.tabs.theory) + (extraTheory[m.id] ? '\n' + extraTheory[m.id] : ''),
      example: toPmmText(m.tabs.example),
      practice: toPmmText(m.tabs.practice) + (extraPractice[m.id] ? '\n' + extraPractice[m.id] : ''),
      task: toPmmText(m.tabs.task),
    },
  };
}

