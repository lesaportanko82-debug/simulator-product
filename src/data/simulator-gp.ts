// GoPractice-style Interactive Simulator Data
// Architecture: module -> steps -> tasks with auto-validation

export type TaskType =
  | 'single_choice'
  | 'multiple_choice'
  | 'text_answer'
  | 'funnel_analysis'
  | 'metric_analysis'
  | 'product_decision'
  | 'prioritization'
  | 'data_interpretation';

export type StepType = 'context' | 'theory' | 'task' | 'feedback' | 'summary';
export type TaskStatus = 'not_started' | 'in_progress' | 'submitted' | 'correct' | 'incorrect' | 'completed';

export interface FunnelRow {
  stage: string;
  users: number;
  conversion: number; // to previous step
  dropoff: number;
}

export interface MetricRow {
  metric: string;
  current: string | number;
  target: string | number;
  trend: 'up' | 'down' | 'flat';
  note: string;
}

export interface Option {
  id: string;
  text: string;
  isCorrect: boolean;
}

export interface GPTask {
  id: string;
  type: TaskType;
  question: string;
  description?: string;
  funnel?: FunnelRow[];
  metrics?: MetricRow[];
  table?: { headers: string[]; rows: (string | number)[][] };
  options?: Option[];
  correctKeywords?: string[]; // for text_answer
  correctOrder?: string[]; // for prioritization
  feedback: {
    correct: string;
    incorrect: string;
    hint: string;
    deepExplanation: string;
  };
}

export interface AITaskDef {
  question: string;
  context: string;
  rubric: string; // criteria for correct answer
}

export interface GPStep {
  id: string;
  type: StepType;
  title: string;
  content: string;
  teamMessage?: { author: string; role: string; avatar?: string; text: string };
  task?: GPTask;
  aiTask?: AITaskDef;
  insight?: string; // highlighted takeaway
}

export interface GPModule {
  id: string;
  title: string;
  subtitle: string;
  description: string;
  difficulty: 'Начальный' | 'Средний' | 'Продвинутый';
  duration: string;
  tags: string[];
  isLocked: boolean;
  steps: GPStep[];
}

export interface GPSimulator {
  id: string;
  title: string;
  description: string;
  company: string;
  role: string;
  modules: GPModule[];
}

